function cleanText(value, maxLength) {
  return String(value || '').trim().slice(0, maxLength);
}

function cleanMode(value) {
  const mode = cleanText(value, 40).toLowerCase();
  if (!MODES.has(mode)) throw new TypeError('unsupported_consultation_mode');
  return mode;
}

function cleanStage(value) {
  const stage = cleanText(value, 30).toLowerCase();
  return STAGES.has(stage) ? stage : 'opening';
}

function cleanHistory(value) {
  if (!Array.isArray(value)) return [];
  return value.slice(-20).flatMap((item) => {
    const role = item?.role === 'assistant' ? 'assistant' : 'user';
    const content = cleanText(item?.content, 4000);
    return content ? [{ role, content }] : [];
  });
}

function cleanMemory(value) {
  if (!Array.isArray(value)) return [];
  return value.slice(-30).map((item) => cleanText(item?.content || item, 500)).filter(Boolean);
}

function cleanContext(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return {};
  const serialized = JSON.stringify(value);
  if (serialized.length > 8000) throw new TypeError('consultation_context_too_large');
  return JSON.parse(serialized);
}

export function buildConsultationMessages(payload, memory = []) {
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) {
    throw new TypeError('payload must be an object');
  }

  const mode = cleanMode(payload.mode || 'general');
  const stage = cleanStage(payload.stage);
  const turn = Math.max(0, Math.min(100, Number(payload.turn) || 0));
  const message = cleanText(payload.message, 6000);
  if (!message) throw new TypeError('consultation_message_required');
  const context = cleanContext(payload.context);
  const history = cleanHistory(payload.history);
  const memories = cleanMemory(memory);

  const runtime = [
    `Текущий раздел: ${mode}.`,
    `Этап разговора: ${stage}.`,
    `Номер реплики пользователя в этой теме: ${turn + 1}.`,
    `Контекст выбранного ритуала: ${JSON.stringify(context)}.`,
    memories.length
      ? `Разрешённая пользователем смысловая память: ${JSON.stringify(memories)}.`
      : 'Смысловая память пуста или отключена.',
    turn === 0
      ? 'Это первая реплика новой темы. Если запрос понятен, ответь сразу; уточняй только недостающий критичный факт.'
      : 'Продолжай с учётом истории и последней функции реплики. Не возвращай разговор на заранее заданный этап.',
    'В самом конце добавь одну невидимую служебную строку: <!--ESOTERIUM_STATE {"stage":"opening|clarifying|symbols|summary|recommendation","summary":"краткий контекст до 500 знаков","memory":"одно значимое сведение до 300 знаков или пустая строка"}-->. Не объясняй её назначение.'
  ].filter(Boolean).join('\n');

  return [
    { role: 'system', content: `${ESOTERIUM_SYSTEM_PROMPT}\n\n## ТЕКУЩАЯ КОНСУЛЬТАЦИЯ\n${runtime}` },
    ...history,
    { role: 'user', content: message }
  ];
}

export function parseEsoteriumResponse(value) {
  const raw = cleanText(value, 20000);
  const pattern = /<!--\s*ESOTERIUM_STATE\s+({[\s\S]*?})\s*-->/i;
  const match = raw.match(pattern);
  const answer = raw.replace(pattern, '').trim();
  const fallback = { stage: 'clarifying', summary: '', memory: '' };
  if (!match) return { answer: answer || raw, state: fallback };

  try {
    const parsed = JSON.parse(match[1]);
    return {
      answer,
      state: {
        stage: cleanStage(parsed?.stage),
        summary: cleanText(parsed?.summary, 500),
        memory: cleanText(parsed?.memory, 300)
      }
    };
  } catch {
    return { answer: answer || raw, state: fallback };
  }
}

export function isConsultationMode(value) {
  return MODES.has(String(value || '').toLowerCase());
}
