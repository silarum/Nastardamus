// Every Minor Arcana now has its own finished 2:3 artwork. Keeping the path in
// the map lets the original 22 Major Arcana remain byte-for-byte untouched.
export const TAROT_MINOR_ARCANA = Object.freeze(MINOR_SUITS.flatMap(([suitName, suitFile]) =>
  MINOR_RANKS.map(([rankName, rankFile]) => [
    `${rankName} ${suitName}`,
    `minor-realistic/${rankFile}-of-${suitFile}.webp`
  ])
));

