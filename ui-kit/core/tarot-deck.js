const minorWhispers = Object.fromEntries(TAROT_MINOR_ARCANA.map(([name]) => {
  const [rank, ...suitParts] = name.split(' ');
  const suit = suitParts.join(' ');
  return [name, `${RANK_WHISPERS[rank]}; ${SUIT_WHISPERS[suit]}`];
}));

export const TAROT_CARD_WHISPERS = Object.freeze({ ...MAJOR_WHISPERS, ...minorWhispers });

export function tarotCardImage(name) {
  const file = TAROT_CARD_IMAGES[name] || 'high-priestess.webp';
  return `/images/cards/${file}`;
}
