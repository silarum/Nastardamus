const CATALOGS = { en: EN, zh: ZH };
let activeLocale = 'ru';

export function normalizeLocale(value) {
  const locale = String(value || '').toLowerCase().replace('_', '-');
  if (locale.startsWith('zh')) return 'zh';
  if (locale.startsWith('en')) return 'en';
  return 'ru';
}

export function setLocale(value) {
  activeLocale = SUPPORTED.has(value) ? value : normalizeLocale(value);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = activeLocale === 'zh' ? 'zh-CN' : activeLocale;
    document.documentElement.dataset.locale = activeLocale;
  }
  return activeLocale;
}

export function getLocale() {
  return activeLocale;
}

export function dateTimeLocale(locale = activeLocale) {
  return locale === 'zh' ? 'zh-CN' : locale === 'en' ? 'en-US' : 'ru-RU';
}

export function translateText(value, locale = activeLocale) {
  const text = String(value ?? '');
  if (locale === 'ru' || !text) return text;
  const catalog = CATALOGS[locale] || {};
  if (catalog[text]) return catalog[text];

  let match = /^Выбрано: (\d+) · минимум 3$/.exec(text);
  if (match) return locale === 'zh' ? `已选择：${match[1]} · 至少 3 项` : `Selected: ${match[1]} · minimum 3`;
  match = /^(.+), найдите одну ясную точку опоры$/.exec(text);
  if (match) return locale === 'zh' ? `${match[1]}，请找到一个清晰的支点` : `${match[1]}, find one clear point of support`;
  match = /^(.*) · (.*)$/.exec(text);
  if (match && catalog[match[2]]) return `${match[1]} · ${catalog[match[2]]}`;
  match = /^(\d+) вращение доступно$/.exec(text);
  if (match) return locale === 'zh' ? `可转动 ${match[1]} 次` : `${match[1]} spin available`;
  match = /^Доступно: (\d+)$/.exec(text);
  if (match) return locale === 'zh' ? `可用：${match[1]}` : `Available: ${match[1]}`;
  match = /^Теперь я знаю ваше имя, (.+)\.$/.exec(text);
  if (match) return locale === 'zh' ? `现在我知道你的名字了，${match[1]}。` : `Now I know your name, ${match[1]}.`;
  match = /^(.+), ваш путь открыт$/.exec(text);
  if (match) return locale === 'zh' ? `${match[1]}，你的道路已经开启` : `${match[1]}, your path is open`;
  return text;
}

